import {CLI_COMMAND_SPECS, CLI_FLAG_SPECS, type CliFlagSpec} from './cliSpec.js';

/**
 * Static, network-free shell completion scripts. Every word emitted here comes
 * from CLI_COMMAND_SPECS / CLI_FLAG_SPECS, so completions stay in parity with
 * the parser and help text by construction.
 */

export const COMPLETION_SHELLS = ['bash', 'zsh', 'fish', 'pwsh'] as const;

export type CompletionShell = (typeof COMPLETION_SHELLS)[number];

export const isCompletionShell = (
  value: string | undefined,
): value is CompletionShell =>
  (COMPLETION_SHELLS as readonly string[]).includes(value ?? '');

const VERSION_FLAG_NAMES = ['--version', '-v'] as const;

const flagTakesValue = (spec: CliFlagSpec): boolean =>
  spec.kind === 'value' ||
  spec.kind === 'csv' ||
  spec.kind === 'number' ||
  spec.kind === 'filter' || spec.kind === 'language';

const allFlagNames = CLI_FLAG_SPECS.flatMap((spec) => spec.names);
const flagWords = [...allFlagNames, ...VERSION_FLAG_NAMES];
const commandWords = CLI_COMMAND_SPECS.map((command) => command.name);
const subcommandSpecs = CLI_COMMAND_SPECS.filter(
  (command) => command.subcommands !== undefined,
);

interface PrevWordCompletion {
  readonly parent: string;
  readonly name: string;
  readonly description: string;
}

const prevWordCompletions: readonly PrevWordCompletion[] = [
  ...subcommandSpecs.flatMap(
    (command) =>
      command.subcommands?.map((sub) => ({
        parent: command.name,
        name: sub.name,
        description: sub.description,
      })) ?? [],
  ),
  ...COMPLETION_SHELLS.map((shell) => ({
    parent: 'completion',
    name: shell,
    description: 'Print a completion script for this shell',
  })),
];
const completionParents = [
  ...new Set(prevWordCompletions.map((entry) => entry.parent)),
];
const childEntries = (parent: string): readonly PrevWordCompletion[] =>
  prevWordCompletions.filter((entry) => entry.parent === parent);

const enumFlagSpecs = CLI_FLAG_SPECS.filter(
  (spec) => spec.values !== undefined && spec.values.length > 0,
);
const plainValueFlagSpecs = CLI_FLAG_SPECS.filter(
  (spec) => flagTakesValue(spec) && spec.values === undefined,
);

/** Rough argument hint for `_arguments`-style specs, derived from `usage`. */
const valueHint = (spec: CliFlagSpec): string => {
  const bracketed = spec.usage.match(/<([^>|,\s]+)/)?.[1];
  return (bracketed ?? spec.usage.split(' ')[1] ?? 'value').replace(
    /[^a-zA-Z].*$/,
    '',
  );
};

const zshEscapeDescription = (text: string): string =>
  text.replace(/[[\]:\\]/g, (char) => `\\${char}`);

const fishEscapeDescription = (text: string): string =>
  text.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

const renderBashCompletion = (): string => {
  const enumCases = enumFlagSpecs
    .map(
      (spec) =>
        `        ${spec.names.join('|')})\n            COMPREPLY=( $(compgen -W "${spec.values?.join(' ')}" -- "$cur") )\n            return\n            ;;`,
    )
    .join('\n');
  const plainValueCase = `        ${plainValueFlagSpecs
    .flatMap((spec) => spec.names)
    .join('|')})\n            return\n            ;;`;
  const subcommandCases = completionParents
    .map(
      (parent) =>
        `        ${parent})\n            COMPREPLY=( $(compgen -W "${childEntries(parent)
          .map((entry) => entry.name)
          .join(' ')}" -- "$cur") )\n            return\n            ;;`,
    )
    .join('\n');

  return `# bash completion for the slothhub CLI.
# Generated by \`slothhub completion bash\`; do not edit by hand.
_slothhub() {
    local cur prev
    COMPREPLY=()
    cur="\${COMP_WORDS[COMP_CWORD]}"
    prev="\${COMP_WORDS[COMP_CWORD-1]}"

    case "$prev" in
${enumCases}
${plainValueCase}
${subcommandCases}
    esac

    if [[ $COMP_CWORD -eq 1 ]]; then
        COMPREPLY=( $(compgen -W "${commandWords.join(' ')}" -- "$cur") )
        return
    fi

    COMPREPLY=( $(compgen -W "${flagWords.join(' ')}" -- "$cur") )
}
complete -o default -F _slothhub slothhub

# Install: save into bash's completion directory or source it from ~/.bashrc:
#   slothhub completion bash > ~/.local/share/bash-completion/completions/slothhub
`;
};

const renderZshCompletion = (): string => {
  const commandEntries = CLI_COMMAND_SPECS.map(
    (command) =>
      `        '${command.name}:${zshEscapeDescription(command.description)}'`,
  ).join('\n');
  const subcommandArrays = completionParents
    .map(
      (parent) =>
        `    local -a ${parent}_actions\n    ${parent}_actions=(\n${childEntries(parent)
          .map(
            (entry) =>
              `        '${entry.name}:${zshEscapeDescription(entry.description)}'`,
          )
          .join('\n')}\n    )`,
    )
    .join('\n');
  const subcommandCases = completionParents
    .map(
      (parent) =>
        `            ${parent})\n                _describe -t actions '${parent} action' ${parent}_actions\n                return\n                ;;`,
    )
    .join('\n');
  const argumentSpecs = CLI_FLAG_SPECS.flatMap((spec) =>
    spec.names.map((name) => {
      const description = zshEscapeDescription(spec.description);
      if (!flagTakesValue(spec)) return `        '${name}[${description}]'`;
      if (spec.values) {
        return `        '${name}[${description}]:${valueHint(spec)}:(${spec.values.join(' ')})'`;
      }
      return `        '${name}[${description}]:${valueHint(spec)}:'`;
    }),
  )
    .concat([
      `        '--version[Print the CLI version]'`,
      `        '-v[Print the CLI version]'`,
      `        '*: :_files'`,
    ])
    .join(' \\\n');

  return `#compdef slothhub
# zsh completion for the slothhub CLI.
# Generated by \`slothhub completion zsh\`; do not edit by hand.
_slothhub() {
    local -a commands
    commands=(
${commandEntries}
    )
${subcommandArrays}

    if (( CURRENT == 2 )); then
        _describe -t commands 'slothhub command' commands
        return
    fi

    if (( CURRENT == 3 )); then
        case "$words[2]" in
${subcommandCases}
        esac
    fi

    _arguments -s \\
${argumentSpecs}
}
compdef _slothhub slothhub

# Install: save as _slothhub in a directory on your fpath, for example:
#   mkdir -p ~/.zfunc && slothhub completion zsh > ~/.zfunc/_slothhub
#   echo 'fpath+=~/.zfunc' >> ~/.zshrc && exec zsh
`;
};

const renderFishCompletion = (): string => {
  const commandLines = CLI_COMMAND_SPECS.map(
    (command) =>
      `complete -c slothhub -n '__fish_use_subcommand' -a ${command.name} -d '${fishEscapeDescription(command.description)}'`,
  );
  const subcommandLines = completionParents.flatMap((parent) => {
    const entries = childEntries(parent);
    const subNames = entries.map((entry) => entry.name).join(' ');
    return entries.map(
      (entry) =>
        `complete -c slothhub -n '__fish_seen_subcommand_from ${parent}; and not __fish_seen_subcommand_from ${subNames}' -a ${entry.name} -d '${fishEscapeDescription(entry.description)}'`,
    );
  });
  const flagLines = CLI_FLAG_SPECS.flatMap((spec) =>
    spec.names.map((name) => {
      const option = name.startsWith('--')
        ? `-l ${name.slice(2)}`
        : `-s ${name.slice(1)}`;
      const requires = flagTakesValue(spec) ? ' -r' : '';
      const values = spec.values ? ` -a '${spec.values.join(' ')}'` : '';
      return `complete -c slothhub ${option}${requires}${values} -d '${fishEscapeDescription(spec.description)}'`;
    }),
  );

  return `# fish completion for the slothhub CLI.
# Generated by \`slothhub completion fish\`; do not edit by hand.
${commandLines.join('\n')}
${subcommandLines.join('\n')}
${flagLines.join('\n')}
complete -c slothhub -l version -d 'Print the CLI version'
complete -c slothhub -s v -d 'Print the CLI version'

# Install: save into fish's completions directory:
#   slothhub completion fish > ~/.config/fish/completions/slothhub.fish
`;
};

const renderPwshCompletion = (): string => {
  const commandList = commandWords.map((name) => `'${name}'`).join(', ');
  const subcommandEntries = completionParents
    .map(
      (parent) =>
        `        ${parent} = @(${childEntries(parent)
          .map((entry) => `'${entry.name}'`)
          .join(', ')})`,
    )
    .join('\n');
  const flagValueEntries = enumFlagSpecs
    .flatMap((spec) =>
      spec.names.map(
        (name) =>
          `        '${name}' = @(${spec.values
            ?.map((value) => `'${value}'`)
            .join(', ')})`,
      ),
    )
    .join('\n');
  const flagList = flagWords.map((name) => `'${name}'`).join(', ');

  return `# PowerShell completion for the slothhub CLI.
# Generated by \`slothhub completion pwsh\`; do not edit by hand.
Register-ArgumentCompleter -Native -CommandName 'slothhub' -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)

    $commands = @(${commandList})
    $subcommands = @{
${subcommandEntries}
    }
    $flagValues = @{
${flagValueEntries}
    }
    $flags = @(${flagList})

    $elements = @($commandAst.CommandElements | ForEach-Object { $_.Extent.Text })
    $previous = if ($elements.Count -ge 2) { $elements[$elements.Count - 2] } else { '' }

    $match = {
        param($values)
        $values | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
            [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
        }
    }

    if ($flagValues.Contains($previous)) { & $match $flagValues[$previous]; return }
    if ($subcommands.Contains($previous)) { & $match $subcommands[$previous]; return }
    if ($wordToComplete -like '-*') { & $match $flags; return }
    if ($elements.Count -le 1 -or $elements[1] -eq $wordToComplete) {
        & $match $commands
        return
    }
    & $match $flags
}

# Install: append to your PowerShell profile or save to a file it sources:
#   slothhub completion pwsh >> $PROFILE
`;
};

export const renderShellCompletionScript = (shell: CompletionShell): string => {
  switch (shell) {
    case 'bash':
      return renderBashCompletion();
    case 'zsh':
      return renderZshCompletion();
    case 'fish':
      return renderFishCompletion();
    case 'pwsh':
      return renderPwshCompletion();
  }
};
