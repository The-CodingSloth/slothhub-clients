import {z} from 'zod'
import {getGalleryImageTextReviewWarnings} from './galleryImageReview.js'
import {isObviousPlaceholderAltText} from './mediaAltText.js'
import type {JsonValue} from './jsonValue.js'

// Sanity image identities carry their intrinsic dimensions; never guess a screenshot ratio.
export const toolFeatureImageAssetSchema = z.string().regex(
  /^image-[a-f0-9]+-[1-9]\d*x[1-9]\d*-(?:png|jpg|webp|avif)$/,
  'Use an uploaded Sanity PNG, JPG, WebP or AVIF image asset with intrinsic dimensions.',
)

export const toolFeatureImageFields = {
  _type: z.literal('image').optional(),
  asset: z.object({_ref: toolFeatureImageAssetSchema, _type: z.literal('reference').optional()}),
  alt: z.string().trim().min(1, 'Describe the feature screenshot.'),
  caption: z.string().trim().min(1).optional(),
  // Generated by the public GROQ projection; authors supply the asset reference.
  url: z.url().refine((value) => {
    const url = new URL(value)
    return url.origin === 'https://cdn.sanity.io' && url.pathname.startsWith('/images/') && !url.username && !url.password && !url.search && !url.hash
  }, 'Use the canonical Sanity image CDN URL.').optional(),
}

export interface ToolFeatureImageDimensions {width: number; height: number}

export function getToolFeatureImageDimensions(assetRef: string): ToolFeatureImageDimensions {
  const reference = toolFeatureImageAssetSchema.parse(assetRef)
  const dimensions = reference.split('-')[2]!.split('x')
  return {width: Number(dimensions[0]), height: Number(dimensions[1])}
}

/** Inspect raw drafts too, so an incomplete image cannot disappear before its warning. */
export function getToolFeatureImageWarnings(value: JsonValue): string[] {
  if (!Array.isArray(value)) return []
  return value.flatMap((item) => {
    const parsed = z.object({title: z.string().optional(), feature: z.string().optional(), image: z.json().optional()}).safeParse(item)
    if (!parsed.success || !parsed.data.image) return []
    const label = `Feature “${parsed.data.title ?? parsed.data.feature ?? 'Untitled'}” screenshot`
    const image = z.object({alt: z.string().nullish(), asset: z.object({_ref: z.string()}).nullish(), review: z.json().optional()}).safeParse(parsed.data.image)
    if (!image.success) return [`${label} needs an uploaded image and descriptive alternative text.`]
    const warnings = !image.data.alt?.trim() || isObviousPlaceholderAltText(image.data.alt)
      ? [`${label} needs descriptive alternative text; replace missing or placeholder text.`] : []
    return [...warnings, ...getGalleryImageTextReviewWarnings([{type: 'image', image: image.data}])
      .map(({message}) => message.replace('Gallery image 1', label))]
  })
}
